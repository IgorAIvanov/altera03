-- ═══════════════════════════════════════════════════════════════════════════
-- Нумератор — один механізм на всі номери застосунку: і коди довідників, і
-- номери документів. Двох механізмів немає свідомо: правило «префікс плюс
-- лічильник, що обнуляється щороку» однакове для накладної та для контрагента,
-- а розведене по двох місцях воно розходиться мовчки.
--
-- КЛЮЧОВЕ РІШЕННЯ: період лічильника задається ЯВНО (`period`) і НЕ виводиться
-- з того, що надруковано в номері. Спокуса вивести його з шаблона («є {YY} —
-- значить щороку») виглядає елегантно і хибна по суті: більшості потрібна
-- нумерація В МЕЖАХ РОКУ, але рік у самому номері друкують далеко не всі.
-- Виведення з шаблона змусило б їх або друкувати рік, або відмовитися від
-- обнуління — тобто формат номера диктував би облікове правило.
--
-- Тоді чому це безпечно? Бо унікальність тримає не форма номера, а ІНДЕКС ПО
-- ДАТІ ДОКУМЕНТА: uq_document_number включає `date_trunc('year', doc_date)`.
-- Дата в документі вже є, тож окремого стовпчика з періодом не заводимо — це
-- було б друге місце для того самого факту, а такі місця розходяться.
--
-- Звідси й межа `period`: рік у виразі індексу зашитий (індекс один на таблицю,
-- а period — рядок конфігурації). `none` лягає без натяжки — при наскрізному
-- лічильнику номери й так не повторюються; `month` вимагає {MM} у шаблоні,
-- інакше січневий і лютневий №1 зіткнулися б у річному ключі. Це перевіряє
-- app.numerator_validate.
-- ═══════════════════════════════════════════════════════════════════════════

-- ── Правило ─────────────────────────────────────────────────────────────────
-- Рядки сіються з manifest.json моделей при sql:assemble
-- (див. _generated/numerators.data.sql) через `on conflict do nothing`:
-- манифест дає УМОВЧАННЯ, далі правило живе своїм життям на admin-екрані,
-- і деплой правку не затирає — так само, як із шаблонами друку.

create table if not exists app.numerator (
  model       varchar(100) primary key,        -- ключ моделі з manifest.json
  name        varchar(255) not null,
  -- Плейсхолдери: {ORG} {TYPE} {YYYY} {YY} {MM} {N…}. Ширина лічильника —
  -- довжина плейсхолдера: {NNNNNN} → 000001. Шаблон — це ВИГЛЯД номера і
  -- більше нічого: період лічильника він не задає.
  template    varchar(50)  not null,
  -- Коли лічильник починається спочатку: none | year | month. Вимагає дати в
  -- області, тобто працює для документів; довідник лишається на `none`.
  period      varchar(10)  not null default 'none',
  -- counter  — лічильник у рядку таблиці. Звичайний DML, тому відкат транзакції
  --            повертає номер: нумерація суцільна. Одночасні записи в ОДНУ
  --            область серіалізуються до кінця транзакції.
  -- sequence — окрема послідовність на область. Не блокує паралельних писарів
  --            і не відкочується, тобто відкат лишає дірку назавжди.
  strategy    varchar(20)  not null default 'counter',
  -- Чи можна виправити виданий номер руками на формі.
  is_editable boolean      not null default true,
  -- Джерело пересіву: де лежать уже видані номери. Це СТРУКТУРНІ факти моделі
  -- (таблиця, колонка з номером, колонки області), а не налаштування: їх пише
  -- деплой із манифеста і ОНОВЛЮЄ при кожній публікації (on conflict do
  -- update лише цих полів), тоді як name/template/period/strategy після
  -- сіяння належать адміністратору. Без них пересів з екрана нумераторів був
  -- би неможливий — екран знає лише ключ моделі. Див. app.numerator_reseed.
  source_table       varchar(100),
  source_column      varchar(100),
  source_org_column  varchar(100),
  source_date_column varchar(100),
  source_filter      text,
  updated_at  timestamptz  not null default now(),
  constraint ck_numerator_strategy check (strategy in ('counter', 'sequence')),
  constraint ck_numerator_period check (period in ('none', 'year', 'month'))
);

-- ── Лічильник ───────────────────────────────────────────────────────────────
-- Один рядок на область. Область — ФАКТИ запису (організація, період з дати),
-- а не те, що надруковано: {ORG} у шаблоні впливає лише на вигляд номера,
-- лічильники організацій окремі завжди — як і в uq_document_number, куди
-- organization_id входить незалежно від шаблона (див. numerator_scope_key).
-- scope_key порожній, коли лічильник наскрізний і області немає (довідник).
-- При strategy = 'sequence' рядок лишається як точка засіву послідовності
-- (див. app.numerator_sequence), але не оновлюється на кожній видачі.

create table if not exists app.numerator_state (
  model      varchar(100) not null references app.numerator (model) on delete cascade,
  scope_key  varchar(100) not null,
  last_value bigint       not null default 0,
  constraint pk_numerator_state primary key (model, scope_key)
);
