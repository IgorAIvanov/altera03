-- Тут колись стояли ДВА засіви, і обидва були прикладними: опис вимірів
-- субконто (`counterparty`, `bank` — довідники ЗАСТОСУНКУ, з іменами його
-- таблиць) і прив'язка субконто до рахунків 311–314, 361, 631… — кодів
-- УКРАЇНСЬКОГО плану рахунків, якого ядро теж не оголошувало.
--
-- Ознака неправильної межі проста: у пакеті ядра не має бути ані коду рахунку
-- конкретного плану, ані імені таблиці застосунку.
--
-- Гірше за саму межу було `on conflict … do update`: ядро лишалося власником
-- слота НАЗАВЖДИ. Застосунок, який ставив на 311 свій вимір (аналітикою
-- поточного рахунку має бути сам рахунок, а не банк: банк із рахунку
-- виводиться, навпаки — ні), після кожного `sql:publish` мовчки отримував назад
-- ядровий. Помилки немає, публікація зелена, а виявляється це не на публікації,
-- а через місяць — у проводці, де замість рахунку стоїть банк.
--
-- Тепер вимір оголошує МОДЕЛЬ, чий довідник ним працює, а прив'язку до
-- рахунків — план рахунків: обидва в застосунку, обидва з `on conflict do
-- nothing`, бо після першого засіву це налаштування установки (той самий поділ,
-- що в нумераторах і шаблонах друку). Зразок — `app/catalog/bank/db/data.sql` і
-- `app/catalog/chart_of_account/db/data.sql` цього репозиторію.
--
-- Порядок у `sql.json` через це має значення: модель, що оголошує вимір, стоїть
-- ВИЩЕ за план рахунків — інакше прив'язка не знайде виміру. Зовнішній ключ на
-- `app.analytic_dimension` зробить це помилкою публікації, а не тихим пропуском.
--
-- app.document_type тут теж немає: типи документів генеруються з manifest.json
-- моделей-документів у _generated/document-types.data.sql.
