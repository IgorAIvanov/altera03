-- Пам'ятка бази — CLAUDE.md для облікової системи, тільки в базі даних.
--
-- Навіщо. Агент знає бухгалтерію: подвійний запис, П(С)БО, послідовність
-- документів. Чого він знати не може — домовленостей ЦЬОГО підприємства: що
-- ТЗР у нас у вартості запасу, що склад №3 — відповідальне зберігання, що
-- «Транзит» у контрагентах це перевізник. Реєстр оголошених обмежень каже,
-- чого не можна; сухий прогін каже, що вийде; обидва — про механіку. Це — про
-- звички, і вивести їх нема звідки.
--
-- Чому в базі, а не файлом у рішенні. Файл в app/ поїхав би в поставку й був
-- би затертий оновленням, а править пам'ятку не той, хто пише код, а той, хто
-- веде облік: у нього немає репозиторію, у нього є екран. Заразом вона їде
-- звичайним каналом (права, `audit_log`) і потрапляє в резервну копію разом з
-- обліком — без пам'ятки відновлена база поводиться інакше, ніж вихідна.
--
-- РЯДКАМИ, а не одним текстом. `CLAUDE.md` — один файл, і спокуса повторити це
-- велика. Але агент пропонує формулювання поштучно, і підтверджувати їх треба
-- теж поштучно; в одному текстовому полі «підтверджено» нема чого чіпляти.
--
-- ДВА ВИДИ, і другий ламає правило «завжди в контексті». Записка (`note`) — це
-- одна думка на рядок, вона їде завжди й тому мусить бути короткою. Тема
-- (`topic`) — це процедура («Порядок закриття місяця»), півтора-три кілобайти,
-- і таких буде десяток: покласти їх усі завжди означало б вивалити в кожну
-- розмову те, що знадобиться в одній із двадцяти.
--
-- Тому в теми зроблено як у скіла: ЗАВЖДИ їде тільки рядок покажчика
-- (`slug` + `title` + `summary`), а тіло агент забирає командою, коли задача
-- збіглася. Найважливіше в покажчику — `summary`, тобто «коли це потрібно»:
-- `close-month` у голові нічого не запускає, а «що робимо перед закриттям
-- місяця й у якому порядку» — запускає. Саме тут такі речі й псують: пишуть
-- заголовок замість приводу відкрити.
--
-- Мови тут немає навмисно. Пам'ятку пише людина тією мовою, якою на цьому
-- підприємстві говорять, і перекладати домовленості підприємства — не справа
-- фреймворку. Це не те саме, що інтерфейс: інтерфейс наш, а це їхнє.
-- ═══════════════════════════════════════════════════════════════════════════

create table if not exists app.agent_note (
  id          bigint generated always as identity primary key,
  -- '*' — уся база; ім'я моделі — нюанс саме цього документа чи довідника.
  -- Так само, як у правах: `model = '*'` означає «усі».
  model_key   varchar(100) not null default '*',
  -- note — одна думка, їде завжди; topic — процедура, завжди їде лише покажчик.
  kind        varchar(20)  not null default 'note',
  -- Далі — тільки в теми. У записки все три порожні, і це не «недозаповнено»:
  -- у неї немає ані імені, ані приводу відкрити, бо відкривати нічого.
  slug        varchar(100),
  title       varchar(200),
  summary     text,
  content     text         not null,
  -- Поки не підтверджено — в контекст агента не їде. Це єдиний запобіжник від
  -- того, щоб агент записав власну догадку, а наступний прочитав її як
  -- домовленість підприємства й послався на неї.
  status      varchar(20)  not null default 'draft',
  -- Хто склав формулювання. Не право й не автор правки (їх знає audit_log), а
  -- походження тексту: підтверджуючи запис агента, людина має бачити, що це
  -- переказ її ж слів, а не витяг із закону.
  source      varchar(20)  not null default 'admin',
  created_at  timestamptz  not null default now(),
  updated_at  timestamptz  not null default now(),
  updated_by  bigint references app.users (id),

  constraint ck_agent_note_status check (status in ('draft', 'confirmed')),
  constraint ck_agent_note_source check (source in ('admin', 'agent')),
  constraint ck_agent_note_kind   check (kind in ('note', 'topic')),
  constraint ck_agent_note_content check (length(btrim(content)) > 0),
  -- Тема без `summary` — тема, про яку агент ніколи не здогадається, що вона
  -- йому потрібна: у покажчику стоятиме порожній рядок. Тому три поля разом.
  constraint ck_agent_note_topic check (
    kind <> 'topic' or (
      length(btrim(coalesce(slug, ''))) > 0
      and length(btrim(coalesce(title, ''))) > 0
      and length(btrim(coalesce(summary, ''))) > 0
    )
  )
);

-- Унікальність `slug` створюється в `migration.sql`, а не тут. Порядок збірки —
-- структура, потім міграції: на базі, заведеній до появи колонки, `create
-- table if not exists` нічого не додає, і індекс по неіснуючій колонці впав би
-- ще до того, як міграція цю колонку заведе.

-- Вхід доставки: підтверджені записи потрібної області. Читається на кожному
-- `GET /api/agent/tools`, тобто на початку кожної розмови.
create index if not exists ix_agent_note_scope
  on app.agent_note (model_key, status);

comment on table  app.agent_note            is 'Пам''ятка бази: домовленості цього підприємства для агента';
comment on column app.agent_note.model_key  is '''*'' — уся база; інакше ключ моделі з manifest.json';
comment on column app.agent_note.content    is 'Текст домовленості. Один запис — одна думка';
comment on column app.agent_note.status     is 'draft | confirmed; у контекст агента їде лише confirmed';
comment on column app.agent_note.source     is 'admin | agent — хто склав формулювання';
