-- Моделі ЯДРА в переліку налаштувань журналу.
--
-- Решту рядків сіє застосунок (`_generated/audit-settings.data.sql` — перелік
-- будується з манифестів при складанні пакета), але моделі ядра манифеста не
-- мають: вони доходять до рантайму без запису в реєстрі й обслуговуються
-- стандартним маршрутом `app.<model>_<command>`. Без цього рядка вкладення
-- лишилися б єдиною моделлю, для якої журнал неможливо ввімкнути з екрана.
--
-- `do nothing`, як і всюди в сіді: рівень після першої публікації належить
-- адміністратору, і деплой його не чіпає.
insert into app.audit_setting (model)
values ('attachment')
on conflict (model) do nothing;
