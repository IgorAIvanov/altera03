-- Довге виконання команди моделі: стан завдання живе в базі, а не в запиті.
--
-- Команда моделі сьогодні живе рівно стільки, скільки живе HTTP-запит. Для
-- переважної більшості команд це правильно й міняти нічого не треба. Але є
-- роботи, які на реальній базі йдуть хвилинами — перенесення даних із
-- зовнішньої системи, закриття місяця, перепроведення періоду, — і для них
-- прив'язка до запиту означає три різні поломки одразу: бухгалтер закрив
-- вкладку, проксі розірвав з'єднання, браузер показав помилку там, де робота
-- насправді доробила. Тому стан завдання виноситься в базу: запит запускає
-- роботу й одразу віддає її id, а хто завгодно потім питає, чим скінчилося.
--
-- ЧОМУ САМЕ ТАБЛИЦЯ, А НЕ ПАМ'ЯТЬ ПРОЦЕСУ. Пам'ять переживає рівно один
-- перезапуск сервера — тобто не переживає жодного. Крім того, стан читають
-- троє різних споживачів (екран опитуванням, агент через MCP, скрипт по HTTP),
-- і жодному з них ми не можемо пообіцяти, що він прийде в той самий екземпляр
-- застосунку: на одній машині їх буває кілька.

create table if not exists app.job (
  id       bigint generated by default as identity primary key,
  -- Що саме виконується. Ті самі `model`/`command`, що в рантаймі моделей:
  -- завдання — це не окрема сутність зі своїм життям, а ВІДКЛАДЕНИЙ виклик
  -- звичайної команди. Звідси й те, що прав воно своїх не має — право
  -- перевіряється те саме й тоді ж, коли й у звичайного виклику.
  model    varchar(100) not null,
  command  varchar(100) not null,

  -- Payload виклику. Тут він зберігається, хоча `app.audit_log` payload
  -- свідомо НЕ зберігає, — і різниця не в недбалості. Журнал накриває кожну
  -- команду, включно зі зміною пароля, тож там payload це ризик без потреби.
  -- Довга команда — навпаки: її параметри і є змістом запуску («дата початку
  -- обліку, організація, чи проводити документи»), без них рядок не пояснює
  -- нічого, а повторити запуск неможливо. Звідси вимога до того, хто оголошує
  -- команду довгою: її payload не має нести таємниць. Команду, чий payload
  -- несе пароль або ключ, довгою оголошувати не можна.
  params   jsonb not null default '{}'::jsonb,

  -- queued   — рядок створений, виконавець ще не взявся;
  -- running  — виконується; живий виконавець підтверджує себе `heartbeat_at`;
  -- done     — скінчилося, `result` містить конверт відповіді;
  -- failed   — впало; `error` містить причину;
  -- cancelled — знято на прохання людини (див. `cancel_requested`).
  state    varchar(20) not null default 'queued',

  -- Прогрес — ДАНІ ЗАВДАННЯ, а не рядок для показу: «розділ 7 із 16, рядків
  -- 12 400» кожна команда рахує по-своєму, і жоден спільний набір колонок їх
  -- не накриє. Пишеться він ПОЗА транзакцією самої роботи (інакше його видно
  -- лише після коміту, тобто ніколи) — за це відповідає рантайм, див.
  -- `job.service.ts`.
  progress jsonb not null default '{}'::jsonb,

  -- Конверт відповіді команди — той самий, що повернув би звичайний виклик.
  -- Тобто той, хто чекав на результат, дістає рівно те, що дістав би без
  -- фонового виконання, і клієнтського коду на два випадки не потрібно.
  result   jsonb,
  error    text,

  started_by  bigint not null references app.users (id) on delete restrict,
  created_at  timestamptz not null default now(),
  started_at  timestamptz,
  finished_at timestamptz,

  -- Хто виконує. Ідентифікатор ЕКЗЕМПЛЯРА процесу, а не машини: на одній
  -- машині застосунків буває кілька, і кожен має прибирати тільки за собою.
  runner_id    varchar(64),
  -- Виконавець стукає сюди раз на кілька секунд. Без цього «впав посеред
  -- роботи» неможливо відрізнити від «ще працює»: рядок лишався б у `running`
  -- назавжди, і другий запуск тієї самої команди був би заборонений навіки.
  heartbeat_at timestamptz,

  -- Зняття — прохання, а не вбивство. Виконавець сам дивиться сюди між
  -- кроками й зупиняється в місці, де зупинятися безпечно. Перервати чужу
  -- транзакцію ззовні можна, але тоді «зняв» означало б «відкотив половину
  -- невідомо чого».
  cancel_requested boolean not null default false,

  constraint ck_job_model   check (model ~ '^[a-z][a-z0-9_]*$'),
  constraint ck_job_command check (command ~ '^[a-zA-Z][a-zA-Z0-9_]*$'),
  constraint ck_job_state   check (state in ('queued', 'running', 'done', 'failed', 'cancelled'))
);

-- Другий запуск тієї самої команди, поки перша працює, — відмова, а не дві
-- конвертації навперегін.
--
-- Тримає це УНІКАЛЬНИЙ ІНДЕКС, а не перевірка перед вставкою: перевірка
-- «чи немає активного завдання» з наступною вставкою — класична гонка, і
-- програє вона рівно там, де ціна найвища (два однакові імпорти в одну базу).
-- Межа — пара (модель, команда) на всю установку, без організації й
-- користувача: те, заради чого це робиться, — перенесення й закриття періоду —
-- чіпає базу цілком, і «дві різні організації паралельно» тут не полегшення, а
-- та сама біда, тільки важча для розуміння.
create unique index if not exists uq_job_active
  on app.job (model, command) where state in ('queued', 'running');

-- Стан своїх завдань — головне читання екрана (опитування раз на дві секунди).
create index if not exists ix_job_user_time
  on app.job (started_by, created_at desc);

-- Прибирання покинутих: виконавця вже немає, а рядок лишився в `running`.
create index if not exists ix_job_alive
  on app.job (heartbeat_at) where state = 'running';
