-- Налаштування установки й користувача — ОДНЕ сховище на обидві області.
--
-- Двох таблиць немає свідомо: правило «значення користувача сильніше за
-- значення установки» мусить бути записане ОДИН раз, інакше воно розійдеться
-- між двома місцями рівно тоді, коли з'явиться третя область. Область задає
-- `user_id`: `null` — установка, інакше — конкретна людина.
--
-- Колонка `user_id` є від першого дня, хоча користувацька область ще не
-- ввімкнена й пишеться лише `null`-рядок. Так зроблено тому, що додати її
-- потім означало б міняти ключ уже наповненої таблиці — дешево закласти,
-- дорого змінити.
--
-- Що взагалі можна налаштувати, каже ЗАСТОСУНОК: рядки сіє його деплой
-- (`on conflict do nothing`), а значення після першого сіву належить
-- адміністратору й перевикочування його не затирає. Той самий поділ, що в
-- нумераторах, шаблонах друку й рівнях журналу. Зворотний бік того самого:
-- змінене в сіді умовчання на вже налаштованій базі НЕ застосується.
create table if not exists app.setting_value (
  id         bigint generated by default as identity primary key,
  key        varchar(100) not null,
  -- null — значення установки; інакше — власника.
  user_id    bigint references app.users (id) on delete cascade,
  -- jsonb, а не text: тип значення оголошує каталог застосунку (число, прапорець,
  -- рядок, посилання), і зберігати все рядком означало б розбирати його на
  -- кожному читанні — причому по-різному в SQL і на клієнті.
  value      jsonb not null,
  updated_at timestamptz not null default now(),
  -- Хто змінив останнім. Журнал змін тут не ведеться: для цього є app.audit_log,
  -- якщо моделі налаштувань увімкнути рівень `changes`.
  updated_by bigint references app.users (id) on delete set null,
  constraint ck_setting_value_key check (key ~ '^[a-z][a-zA-Z0-9_.]*$')
);

-- Унікальність — двома ЧАСТКОВИМИ індексами, а не первинним ключем
-- (key, user_id): у PostgreSQL колонка первинного ключа не буває null, а
-- «рядок установки» — це саме null. Два індекси кажуть те саме, що сказав би
-- складений ключ: один рядок установки на ключ і один рядок на пару
-- «ключ + користувач».
create unique index if not exists uq_setting_value_app
  on app.setting_value (key) where user_id is null;
create unique index if not exists uq_setting_value_user
  on app.setting_value (key, user_id) where user_id is not null;
