/**
 * Контракт каналу приймання — те, що бачить застосунок.
 *
 * Тут навмисно немає жодного слова про 1С, BAS чи Excel: джерело — рядок,
 * який називає застосунок разом із набором правил конвертації. Ядро возить
 * байти й стереже цілісність; ЩО замовляти в джерела, воно не знає й знати не
 * повинне.
 */

/** Сесія, як її бачить гак плану. */
export interface ImportSessionContext {
  id: string;
  source: string;
  /** Параметри перенесення, які ядро не тлумачить: дата початку, організація… */
  params: Record<string, unknown>;
  /** Що адаптер сказав про себе при спарюванні. `null` — ще не спарувався. */
  passport: Record<string, unknown> | null;
  /**
   * Пункти плану, дані по яких УЖЕ прийнято цілими партіями.
   *
   * Саме готові: зіпсована партія прийнятою не вважається, інакше пункт зник
   * би з плану, не принісши даних.
   */
  done: string[];
}

/**
 * Один пункт плану: що адаптер має вивантажити наступним.
 *
 * `query` — ім'я пункту, і воно ж стає іменем партії. Ядро в нього не
 * заглядає; решта полів довільна — туди застосунок кладе текст запиту, відбори,
 * розмір частини, усе, про що домовився зі своїм адаптером.
 */
export interface ImportPlanItem {
  query: string;
  [key: string]: unknown;
}

/**
 * Гак плану — ЄДИНЕ місце, де застосунок вирішує, що замовити.
 *
 * Кличеться двічі: при спарюванні (адаптер отримує план разом із токеном) і на
 * `GET /api/import/plan/next` — дозапит за фактом того, що вже прийшло. Тобто
 * керування їде даними ОДИН раз, а далі адаптер шле сам; черги завдань для
 * самого перенесення не потрібно.
 *
 * Не заданий — план порожній. Це робоча конфігурація: канал лишається придатним
 * для джерел, які самі знають, що везти (файл, вивантаження з каси).
 */
export type ImportPlanHook = (
  session: ImportSessionContext,
) => ImportPlanItem[] | Promise<ImportPlanItem[]>;

/** Налаштування каналу приймання. */
export interface ImportConfig {
  plan: ImportPlanHook | null;
  /** Скільки живе код спарювання. Хвилини, бо його диктують голосом. */
  pairingTtlMinutes: number;
  /** Скільки живе токен каналу. Перенесення — робота на дні, не на місяці. */
  tokenTtlHours: number;
  /** Максимум елементів в одній частині пакета. */
  maxPartItems: number;
}
