import { t } from "@client/locale.ts";
import { generatedModelRegistry } from "../_generated/model-registry.generated.ts";

/**
 * Людська назва моделі за її технічним ключем (`chart_of_account` → «План
 * рахунків»).
 *
 * Ключ моделі — те, що лежить у журналі й у налаштуваннях журналу; людині його
 * показувати нема сенсу, а окремого словника назв заводити нема з чого: назва
 * вже є в локалях самої моделі (`<model>.titleMany`), і їде разом із нею.
 *
 * `t()` повертає сам ключ, коли перекладу немає, — і саме це тут ознака того,
 * що моделі в локалях немає (службові моделі ядра її не мають). Тоді чесніше
 * показати технічне ім'я, ніж «attachment.titleOne».
 *
 * Живе в `shared/`, бо власників двоє — журнал і його налаштування; два
 * однакові хелпери в сусідніх екранах розійшлися б мовчки.
 */
export function modelTitle(key: string): string {
  for (const suffix of ["titleOne", "titleMany"]) {
    const value = t(`${key}.${suffix}`);
    if (value !== `${key}.${suffix}`) return value;
  }
  return key;
}

/**
 * Ключі моделей, чия НАЗВА містить підрядок.
 *
 * Потрібне пошуковому рядку списків, де в колонці стоїть назва, а в базі —
 * ключ: інакше «Банки» не знаходить нічого, і виглядає це як зламаний пошук, а
 * не як домовленість про переклад. Шукати на боці бази неможливо за побудовою —
 * назва живе в локалях КЛІЄНТА (той самий довід, що з маркерами `@[…]`: сервер
 * тексту не перекладає, бо мови користувача не знає).
 *
 * Тому збіг рахує клієнт і передає в payload готовий перелік ключів, а SQL
 * додає його до звичайного пошуку по ключу через `or`. Перелік беремо з
 * реєстру, а не зі сторінки: шукають по всьому списку, а на екрані двадцять
 * рядків із двохсот.
 */
export function modelKeysMatching(search: string): string[] {
  const needle = search.trim().toLocaleLowerCase();
  if (!needle) return [];

  return Object.keys(generatedModelRegistry)
    .filter((key) => modelTitle(key).toLocaleLowerCase().includes(needle));
}
