create table if not exists app.interface (
	id bigint generated by default as identity primary key,
	code varchar(100) not null unique,
	name varchar(255) not null,
	is_active boolean not null default true,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now()
);

create table if not exists app.interface_menu (
	id bigint generated by default as identity primary key,
	interface_id bigint not null references app.interface(id) on delete cascade,
	menu_id bigint not null references app.menu(id) on delete cascade,
	sort_order int not null default 0,
	is_active boolean not null default true,
	created_at timestamptz not null default now(),
	updated_at timestamptz not null default now(),
	constraint uq_interface_menu unique (interface_id, menu_id)
);

