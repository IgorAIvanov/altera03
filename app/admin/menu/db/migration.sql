create index if not exists ix_interface_is_active on app.interface (is_active);

create index if not exists ix_interface_menu_interface_order
	on app.interface_menu (interface_id, sort_order, id);

create index if not exists ix_interface_menu_menu on app.interface_menu (menu_id);
create index if not exists ix_interface_menu_is_active on app.interface_menu (is_active);

