-- Каталог налаштувань установки: ЩО можна налаштувати й з чого починається
-- значення. Умовчання лежить саме тут, а не в схемі екрана, — це єдине його
-- місце, і читає його SQL так само, як клієнт.
--
-- `on conflict do nothing`: значення після першого сіву належить адміністратору,
-- і перевикочування застосунку його не затирає. Зворотний бік — змінене тут
-- умовчання на вже налаштованій базі НЕ застосується; щоб зрушити його свідомо,
-- потрібна міграція.
--
-- Поле `values` екрана будується з цих же ключів (app/admin/setting/setting.schema.ts).
insert into app.setting_value (key, user_id, value)
select v.key, null, v.value
from (values
  -- Скільки рядків показувати в списках за умовчанням.
  ('list.pageSize',        '20'::jsonb),
  -- Стеля вивантаження в Excel: вивантажується весь відбір, і без стелі
  -- випадковий відбір на мільйон рядків поклав би вкладку.
  ('list.exportRowLimit',  '10000'::jsonb)
) as v(key, value)
on conflict do nothing;
