/**
 * Гарячі клавіші оболонки — розпізнавання, окремо від виконання.
 *
 * Один канал клавіатури на застосунок: слухач висить у `tab-controller`, а не
 * на кожному екрані. Причина не в охайності — панелі ВСІХ відкритих вкладок
 * лежать у DOM одночасно (схована лише неактивна), тож слухач на екрані
 * розіслав би Ctrl+S у всі відкриті форми разом.
 *
 * Сюди ж згодом стане приймання сканера штрих-кода: він працює як клавіатура
 * (швидка серія символів і Enter), і розрізняти його від людського вводу
 * доведеться в тій самій точці — за темпом натискань.
 *
 * Модуль без DOM навмисно — щоб розкладка перевірялася пробами
 * (`shortcuts_test.ts`), а не очима.
 *
 * ## Черга на клавішу
 *
 * Оболонка діє ОСТАННЬОЮ: спершу компонент (список пікера, календар, комірка),
 * потім модальне вікно, і лише тоді вкладка. Тримається це на двох правилах:
 *
 *  1. **Обробив — познач**: `e.preventDefault()` у тому, хто клавішу забрав.
 *     Оболонка пропускає подію з `defaultPrevented`.
 *  2. **Свій глобальний слухач вішай на `document`, не на `window`.** Слухач
 *     оболонки — на `window` і зареєстрований на старті, тобто РАНІШЕ за
 *     будь-який екран; при однаковій цілі він отримав би подію першим, і
 *     правило (1) не спрацювало б. `document` у ланцюжку спливання стоїть
 *     перед `window`, тож порядок стає визначеним і не залежить від того,
 *     коли створили екран.
 */

/** Дія, яку просить клавіша. Виконує оболонка, а не цей модуль. */
export type ShortcutCommand = "save" | "create" | "close" | "default";

/** Те з `KeyboardEvent`, що потрібне для розпізнавання. */
export interface KeyStroke {
  /** ФІЗИЧНА клавіша (`KeyS`, `Escape`, `Insert`) — див. коментар нижче. */
  code: string;
  ctrlKey: boolean;
  metaKey: boolean;
  altKey: boolean;
  shiftKey: boolean;
}

/**
 * Клавіша → дія; `null` — не наша комбінація.
 *
 * Дивимося на `code`, а не на `key`, і це принципово: `key` віддає СИМВОЛ
 * поточної розкладки, тож у кирилиці Ctrl+S приходить як «ы» або «і» — і
 * сполучення мовчки перестало б працювати рівно там, де застосунком і
 * користуються. `code` називає фізичну клавішу й від розкладки не залежить.
 *
 * Alt не бере участі в жодному сполученні: комбінації з ним належать меню
 * браузера й системі.
 */
export function matchShortcut(stroke: KeyStroke): ShortcutCommand | null {
  if (stroke.altKey || stroke.shiftKey) return null;
  const mod = stroke.ctrlKey || stroke.metaKey;

  if (stroke.code === "KeyS") return mod ? "save" : null;
  // Ctrl+Enter — кнопка за замовчуванням форми. Цифровий Enter теж: для
  // оператора це та сама клавіша, і різниця в `code` його не обходить.
  if (stroke.code === "Enter" || stroke.code === "NumpadEnter") return mod ? "default" : null;
  if (mod) return null;
  if (stroke.code === "Insert") return "create";
  if (stroke.code === "Escape") return "close";
  return null;
}

/**
 * Що екран уміє у відповідь на гарячу клавішу. Усе необов'язкове: оболонка
 * кличе те, що є, і мовчить, якщо методу немає — тоді список не «зберігається»,
 * а форма редагування не створює записів.
 */
export interface ShortcutTarget {
  /** Ctrl+S. Реалізує `BaseUI` — діє лише там, де є що зберігати. */
  hotkeySave?(): void;
  /** Insert. Реалізує `ModelListBase`. */
  hotkeyCreate?(): void;
  /**
   * Ctrl+Enter — кнопка за замовчуванням екрана. У формі редагування це
   * «Зберегти й закрити» (у підвалі вона `btn-primary`).
   */
  hotkeyDefault?(): void;
}
