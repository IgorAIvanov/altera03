/**
 * Яка вкладка мусить бути відкритою — уся логіка вибору смуги вкладок.
 *
 * Окремо від компонента й без DOM навмисно: тут два правила, обидва помітні
 * лише в рідкісний момент (перша відмальовка, невдала перевірка), тож рукою їх
 * перевіряють раз, а проба — щоразу. Той самий поділ, що в `tabs/tab-url.ts`.
 */

export interface TabFocusState {
  key: string;
  /**
   * Секція цієї вкладки просить фокус — при невдалій перевірці `BaseUI` ставить
   * `pendingFocus` ПЕРШІЙ секції з помилкою.
   */
  focusRequested: boolean;
}

/**
 * Порядок джерел: прохання фокуса → поточна вкладка → перша.
 *
 * Прохання сильніше за вибір користувача, і саме в цьому суть: помилка може
 * бути в СХОВАНІЙ таблиці (база перевіряє всі секції, включно з невидимими), і
 * тоді банер каже «Рядок 2, «Сума»…», а рядка на екрані немає. Зате це
 * одноразова подія, а не стан: щойно ціль фокуса спожита, вкладку більше ніхто
 * не смикає — інакше користувача повертало б назад щоразу, коли він пішов
 * подивитися сусідню частину, не виправивши цю.
 *
 * Зникла вкладка (форма перебудувала перелік) заміняється першою: порожня
 * панель гірша за будь-яку показану.
 */
export function activeTabKey(tabs: readonly TabFocusState[], current: string): string {
  const requested = tabs.find((tab) => tab.focusRequested);
  if (requested && requested.key !== current) return requested.key;
  if (tabs.some((tab) => tab.key === current)) return current;
  return tabs[0]?.key ?? "";
}
