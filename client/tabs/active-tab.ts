import { Signal } from "signal-polyfill";

/** Чим вкладка описана: рівно те, з чого будується посилання на неї. */
export interface TabContext {
  route: string;
  modelId: string | null;
}

/**
 * Контекст активної вкладки — окремим модулем, а не властивістю контролера.
 *
 * Потрібен він тому, хто до контролера не має стосунку: кнопка зауваження стоїть
 * у шапці ЗАСТОСУНКУ, а знає, на якому екрані людина, лише оболонка. Передати
 * властивістю не виходить — між ними чужий елемент, який фреймворк лише
 * вставляє.
 *
 * Сигналом, а не подією шини: підписник з'являється й зникає разом із шапкою, а
 * значення потрібне йому й у момент появи. Подія дала б лише зміни, і кнопка,
 * створена після перемикання вкладки, лишилася б без контексту до наступного.
 *
 * Модуль навмисно порожній від поведінки: його імпортують значенням і з
 * оболонки, і з застосунку, тож усе, що сюди потрапить, поїде в обидва чанки.
 */
const _active = new Signal.State<TabContext | null>(null);

/** Активна вкладка або `null` — коли відкрита домашня сторінка. */
export const activeTab = (): TabContext | null => _active.get();

/** Кличе лише `tab-controller`: власник вкладок один. */
export function setActiveTab(value: TabContext | null): void {
  const prev = _active.get();
  if (prev?.route === value?.route && prev?.modelId === value?.modelId) return;
  _active.set(value);
}
