/**
 * Організаційний контекст — те, що фреймворк мусить знати про організації, і не
 * більше.
 *
 * ЧОМУ ІНЖЕКЦІЯ, А НЕ ВЛАСНИЙ СТАН. «Поточна організація» належить
 * ЗАСТОСУНКУ: її показує й міняє його шапка, вона переживає перезавантаження в
 * його сховищі, і вона ж підставляється в нові документи та у фільтри звітів —
 * усе це облікова політика, а не механіка таблиць. Але одну річ фреймворк без
 * неї зробити не може: журнал документів мусить відкриватися звуженим на ту
 * організацію, у якій працюють, бо колонка `organization_id` живе в
 * `app.document`, тобто в ядрі, і застосунку нема куди повісити цей відбір.
 *
 * Тому фреймворк не заводить свого поняття організації, а ПРИЙМАЄ його ззовні
 * — тим самим прийомом, яким `bootstrap()` отримує все на сервері. Межа
 * лишається там, де була, а десять журналів застосунку перестають писати
 * однакову панель.
 *
 * Реєструють контекст ОДИН раз, у composition root застосунку, ДО монтування
 * оболонки:
 *
 * ```ts
 * // app/main.ts
 * setOrganizationContext({
 *   current: () => currentOrg(),
 *   list: () => knownOrgs(),
 * });
 * ```
 *
 * Обидва методи читаються НА КОЖЕН РЕНДЕР, а не запам'ятовуються: якщо за ними
 * стоять сигнали застосунку (а в нас стоять), екрани-`SignalWatcher`
 * перемальовуються самі, коли організацію перемкнули в шапці.
 *
 * Без реєстрації фреймворк поводиться так, наче організація одна: відбір не
 * малюється, умовчання не сіється. Це свідомо — застосунок без організацій
 * (а такі бувають) не має бачити механізму, якого не вмикав.
 */

/** Організація так, як її бачить відбір: id і назва. */
export interface OrgRef {
  id: string;
  name: string;
}

export interface OrganizationContext {
  /** Організація, у якій зараз працюють. `null` — не вибрана. */
  current(): OrgRef | null;
  /**
   * Організації, доступні користувачеві.
   *
   * Порожній масив означає «ще не знаємо» — саме тому відбір ховається лише
   * при РІВНО одній організації, а не при «менше двох»: помилятися тут треба
   * в бік «показати», бо зайвий відбір видно й можна не чіпати, а відсутнього
   * не викличеш ніяк.
   */
  list(): readonly OrgRef[];
}

let context: OrganizationContext | null = null;

/** Зареєструвати контекст. `null` — зняти (потрібно хіба що пробам). */
export function setOrganizationContext(value: OrganizationContext | null): void {
  context = value;
}

/** Організація, у якій працюють, або `null`. */
export function currentOrganization(): OrgRef | null {
  return context?.current() ?? null;
}

/** Відомі організації; порожньо — контексту немає або їх ще не завантажили. */
export function knownOrganizations(): readonly OrgRef[] {
  return context?.list() ?? [];
}

/**
 * Чи показувати відбір за організацією.
 *
 * Одна організація — механізму не показуємо взагалі: відбір, який нічого не
 * відбирає, це не нейтральна дрібниця, а зайвий орган керування на екрані, у
 * який клікають. У більшості установок організація справді одна.
 */
export function organizationFilterApplies(): boolean {
  return knownOrganizations().length > 1;
}
